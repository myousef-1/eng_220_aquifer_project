"""Export every chart as a static image for the report, slides, and docs site.

Run from the repository root:

    pip install kaleido          # one-time; only needed for exporting images
    python -m analysis.export_figures
    python -m analysis.export_figures groundwater_trends rio_puerco_visits   # just some

Writes, for each chart in ``charts.ALL_CHARTS``:
    report/figures/<key>.pdf   vector version for the LaTeX report, without the baked-in
                               title (the report writes its own caption)
    report/figures/<key>.png   the report version with title, scope, and source baked in
    docs/figures/<key>.png     the app version (with pictograms where a chart has them,
                               see charts.PICTOGRAPH_CHARTS), for the docs site and slides
    report/analysis_figures.tex  a ready-to-paste LaTeX figure block for every chart

The six charts in ``charts.PICTOGRAPH_CHARTS`` are exported twice: the pictograph
version to docs/figures/ and the plain version to report/figures/. The numbers,
titles, and findings are the same; only the marks (and a sentence of the caption) differ.

Also writes ``analysis/figure_index.csv``: one row per chart with its title,
scope, research questions, and findings, so the report and docs can be checked
against the charts.

kaleido (the Plotly image exporter) isn't in requirements.txt on purpose: the
live app doesn't need it. Static maps are drawn without a street basemap
(tiles need internet access); the app's interactive maps have one.
"""

from __future__ import annotations

import sys
import time

import pandas as pd

from . import charts
from .data import ROOT

REPORT_DIR = ROOT / "report" / "figures"
DOCS_DIR = ROOT / "docs" / "figures"


def export(keys: list[str] | None = None, pdf: bool = True) -> pd.DataFrame:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    rows = []
    for fn in charts.ALL_CHARTS:
        if keys and fn.__name__ not in keys:
            continue
        t0 = time.time()
        c = fn()  # pictograph version where one exists: for the docs site and slides
        (DOCS_DIR / f"{c.key}.png").write_bytes(c.static().to_image(format="png", scale=2))
        if fn.__name__ in charts.PICTOGRAPH_CHARTS:
            c = fn(pictograph=False)  # the report keeps the plain version
        (REPORT_DIR / f"{c.key}.png").write_bytes(c.static().to_image(format="png", scale=2))
        if pdf:
            (REPORT_DIR / f"{c.key}.pdf").write_bytes(c.static(with_text=False).to_image(format="pdf"))
        rows.append({
            "key": c.key,
            "title": c.title,
            "subtitle": c.subtitle,
            "caption": c.caption,
            "scope": c.scope,
            "research_questions": " ".join(str(q) for q in c.rqs),
            "findings": " | ".join(f"{lab}: {txt}" for lab, txt in c.findings),
            "source": c.source,
        })
        print(f"  {c.key:<45} {time.time() - t0:4.1f}s")
    index = pd.DataFrame(rows)
    if not keys:
        index.to_csv(ROOT / "analysis" / "figure_index.csv", index=False)
        write_latex_figures(index)
    return index


def _tex(s: str) -> str:
    """Escape text for LaTeX."""
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
           "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
           "≥": r"$\geq$", "≤": r"$\leq$", "ρ": r"$\rho$", "µ": r"$\mu$", "²": r"\textsuperscript{2}",
           "³": r"\textsuperscript{3}", "°": r"\textdegree{}", "→": r"$\rightarrow$", "†": r"\dag{}",
           "‡": r"\ddag{}", "·": r"\textperiodcentered{}", "ñ": r"\~{n}"}
    return "".join(rep.get(ch, ch) for ch in s)


def _end(text: str) -> str:
    """Make sure a sentence ends with a period."""
    text = str(text).strip()
    return text if text.endswith((".", "!", "?")) else text + "."


def write_latex_figures(index: pd.DataFrame) -> None:
    """report/analysis_figures.tex: one figure environment per chart, with a caption
    built from the chart's own title, scope, and source. Copy the ones you need
    into report.tex (the report already uses \\graphicspath{{figures/}})."""
    out = ["% Generated by `python -m analysis.export_figures`. Copy figure blocks into report.tex.",
           "% figure* spans both columns; change to figure and width=\\linewidth for one column.", ""]
    for _, r in index.iterrows():
        out += [
            "\\begin{figure*}[t]",
            "  \\centering",
            f"  \\includegraphics[width=\\textwidth]{{{r['key']}}}",
            f"  \\caption{{{_tex(_end(r['title']))} {_tex(_end(r['subtitle']))} {_tex(_end(r['caption']))} "
            f"Scope: {_tex(_end(r['scope']))} Source: {_tex(_end(r['source']))}}}",
            f"  \\label{{fig:{r['key'].split('__')[0]}}}",
            "\\end{figure*}",
            "",
        ]
    (ROOT / "report" / "analysis_figures.tex").write_text("\n".join(out), encoding="utf-8")


if __name__ == "__main__":
    print("Exporting figures to report/figures/ and docs/figures/ ...")
    export(sys.argv[1:] or None)
    print("Done. Run `python -m analysis.write_docs` to refresh the docs pages too.")
